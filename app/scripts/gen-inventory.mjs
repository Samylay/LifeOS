import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDir, "..");

function walk(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(fullPath) : [fullPath];
  });
}

function routeFromFile(file, kind, appDir) {
  const segments = path.relative(appDir, path.dirname(file)).split(path.sep)
    .filter((segment) => segment && !(segment.startsWith("(") && segment.endsWith(")")));
  if (kind === "api") segments.shift();
  return `/${segments.join("/")}`.replace(/\/$/, "") || "/";
}

function methodsFor(file) {
  const source = fs.readFileSync(file, "utf8");
  return [...source.matchAll(/export\s+(?:async\s+)?(?:function|const)\s+(GET|POST|PUT|PATCH|DELETE)\b/g)]
    .map((match) => match[1]);
}

export function generate(root) {
  const absoluteRoot = path.resolve(root);
  const appDir = path.join(absoluteRoot, "src/app");
  const files = walk(appDir);
  const entries = files.flatMap((file) => {
    const kind = path.basename(file) === "page.tsx" ? "page"
      : path.basename(file) === "route.ts" && path.relative(appDir, file).split(path.sep)[0] === "api" ? "api"
      : null;
    if (!kind) return [];
    const route = routeFromFile(file, kind, appDir);
    const params = [...route.matchAll(/\[([^\]]+)\]/g)].map((match) => match[1]);
    const colocated = fs.readdirSync(path.dirname(file)).some((name) => /.+\.test\..+/.test(name));
    return [{
      kind,
      route,
      file: path.relative(absoluteRoot, file).split(path.sep).join("/"),
      methods: kind === "api" ? methodsFor(file) : [],
      dynamic: params.length > 0,
      params,
      hasColocatedTest: colocated,
    }];
  });
  entries.sort((a, b) => a.route.localeCompare(b.route) || a.kind.localeCompare(b.kind) || a.file.localeCompare(b.file));
  return entries;
}

function renderMarkdown(entries) {
  const rows = entries.map(({ kind, route, methods, dynamic, params, hasColocatedTest }) => {
    const methodText = methods.join(", ") || "—";
    return `| ${route} | ${kind} | ${methodText} | ${dynamic ? params.join(", ") : "—"} | ${hasColocatedTest ? "yes" : "no"} |`;
  });
  return [
    "# Routes",
    "",
    "Generated by `node scripts/gen-inventory.mjs`.",
    "",
    "| Route | Kind | Methods | Params | Colocated test |",
    "|-------|------|---------|--------|----------------|",
    ...rows,
    "",
  ].join("\n");
}

function renderJson(entries) {
  return `[` + (entries.length ? `\n${entries.map((entry) => `  ${JSON.stringify(entry)}`).join(",\n")}\n` : "") + `]\n`;
}

function writeOutputs(root, entries) {
  const docsDir = path.join(root, "docs");
  fs.mkdirSync(docsDir, { recursive: true });
  fs.writeFileSync(path.join(docsDir, "routes.json"), renderJson(entries));
  fs.writeFileSync(path.join(docsDir, "routes.md"), renderMarkdown(entries));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const entries = generate(appRoot);
  if (process.argv.includes("--check")) {
    const expected = new Map([
      [path.join(appRoot, "docs/routes.json"), renderJson(entries)],
      [path.join(appRoot, "docs/routes.md"), renderMarkdown(entries)],
    ]);
    let differs = false;
    for (const [file, content] of expected) {
      if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) {
        console.error(`${path.relative(appRoot, file)} differs`);
        differs = true;
      }
    }
    if (differs) process.exitCode = 1;
  } else {
    writeOutputs(appRoot, entries);
  }
}
